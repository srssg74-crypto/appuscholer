const M=require('./mdpages.js');let f=0;
const ok=(c,m)=>{console.log((c?'ok   ':'FAIL ')+m);if(!c)f++};
const kind=t=>/^abstract/i.test(t)?'abstract':/method/i.test(t)?'methods':/result/i.test(t)?'results':/reference/i.test(t)?'references':'other';
let r=M.parse('# Sleep and Anxiety\n\n<!-- page 1 -->\n## Abstract\nText one.\n\n<!-- page 2 -->\n## Methods\n### Participants\nN = 120.\n\n<!-- page 3 -->\n## Results\nr = .41\n',kind);
ok(r.how==='markers'&&r.pages.length===3,'comment markers give 3 pages');
ok(r.title==='Sleep and Anxiety','one # title with ## sections: title kept apart');
ok(r.sections.map(s=>s.kind+'@'+s.page).join()==='abstract@1,methods@2,results@3','sections with kind and page');
ok(r.sections[1].subs[0].title==='Participants'&&r.sections[1].subs[0].page===2,'### becomes a subsection');
ok(!/#|<!--/.test(r.pages.join('')),'heading marks and comments are stripped from page text');
r=M.parse('{0}------------------------------------------------\nFirst\n\n{1}------------------------------------------------\nSecond');
ok(r.how==='markers'&&r.pages[0].trim()==='First'&&r.pages[1].trim()==='Second','zero-based {n}---- markers');
r=M.parse('--- Page 4 ---\nA\n--- Page 5 ---\nB');
ok(r.how==='markers'&&r.pages.length===5&&r.pages[3].trim()==='A'&&r.pages[4].trim()==='B'&&r.pages[0]==='','printed page numbers are kept; earlier pages stay empty');
r=M.parse('[Page 2]\nA\n[Page 1]\nB');
ok(r.how!=='markers','markers out of order are not trusted');
r=M.parse('one\fTwo\fthree');ok(r.how==='formfeed'&&r.pages.length===3,'form feed is a page break');
const long=Array.from({length:40},(_,i)=>'Paragraph '+i+' '+'word '.repeat(120)).join('\n\n');
r=M.parse(long);ok(r.how==='none'&&r.pages.length>3&&r.notes.length===1&&/no page numbers/.test(r.notes[0]),'no markers: cut into parts, with a note');
r=M.parse('See [the scale](http://x.org) and ![fig](a.png) **bold** `code`.');
ok(r.pages[0]==='See the scale and  bold code.','links, images, bold and code are cleaned: '+JSON.stringify(r.pages[0]));
r=M.parse('## One\nx\n## Two\ny',kind);ok(r.sections.length===2&&r.title==='','no # title: ## are sections');
r=M.parse('');ok(r.pages.length<=1&&r.sections.length===0,'empty file is safe');
r=M.parse('## Methods\nसहभागी १२० छात्र थे।',kind);ok(r.pages[0].indexOf('सहभागी १२० छात्र थे।')>0,'Hindi text passes through');
console.log(f?'FAILED '+f:'ALL MARKDOWN TESTS PASSED');process.exit(f?1:0);
